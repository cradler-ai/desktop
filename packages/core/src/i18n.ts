// Tiny i18n: the app picks the locale from the system language at startup.
// Core and the desktop app share one `t()`; the desktop registers its own messages.

export type Locale = 'zh' | 'en';
type Dict = Record<string, string>;

let current: Locale = 'zh';
const dicts: Record<Locale, Dict> = { zh: {}, en: {} };

export function setLocale(l: Locale): void {
  current = l;
}

export function getLocale(): Locale {
  return current;
}

/** System languages → our locale. Chinese → zh, everything else → en. */
export function pickLocale(langs: readonly string[] | undefined): Locale {
  for (const l of langs ?? []) {
    if (/^zh\b/i.test(l)) return 'zh';
    if (/^en\b/i.test(l)) return 'en';
  }
  return 'en';
}

export function registerMessages(locale: Locale, dict: Dict): void {
  Object.assign(dicts[locale], dict);
}

export function t(key: string, vars?: Record<string, string | number | undefined>): string {
  const s = dicts[current][key] ?? dicts.zh[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] == null ? '' : String(vars[k]))) : s;
}

